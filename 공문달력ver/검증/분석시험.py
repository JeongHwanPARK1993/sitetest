def kind_ok(want, got):
    return want is None or want == got


def run(verbose=True):
    fail = 0
    for text, want, note in CASES:
        res = core.analyze(HEAD + text, today=TODAY)
        got = [(str(c["date"]), c["kind"]) for c in res["candidates"] if c["checked"]]
        ok = len(got) == len(want) and all(g[0] == w[0] and kind_ok(w[1], g[1]) for g, w in zip(sorted(got), sorted(want)))
        if not ok:
            fail += 1
        if verbose and (not ok):
            allc = [(str(c["date"]), c["kind"], c["checked"]) for c in res["candidates"]]
            print("✘ [%s] %s\n    기대 %s / 결과 %s\n    후보 전체 %s" % (note, text, want, got, allc))
    print("통과 %d / %d" % (len(CASES) - fail, len(CASES)))
    return fail


if __name__ == "__main__":
    sys.exit(1 if run() else 0)
